CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    email VARCHAR(254) NOT NULL CHECK (email = lower(email)),
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'SALES_AGENT')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(120) NOT NULL CHECK (length(trim(customer_name)) > 0),
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(20),
    enquiry_message TEXT NOT NULL CHECK (length(trim(enquiry_message)) BETWEEN 1 AND 4000),
    source VARCHAR(20) NOT NULL CHECK (source IN ('WEBSITE', 'EMAIL', 'MANUAL', 'OTHER')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'CONTACTED', 'QUALIFIED', 'WON', 'LOST')),
    priority VARCHAR(20) NOT NULL CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    assigned_user_id BIGINT REFERENCES users(id),
    fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT leads_fingerprint_key UNIQUE (fingerprint)
);

CREATE INDEX leads_created_at_idx ON leads (created_at DESC, id DESC);
CREATE INDEX leads_assignee_created_at_idx ON leads (assigned_user_id, created_at DESC, id DESC);
CREATE INDEX leads_status_idx ON leads (status);
CREATE INDEX leads_priority_idx ON leads (priority);
CREATE INDEX leads_source_idx ON leads (source);

CREATE TABLE activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT REFERENCES leads(id) ON DELETE SET NULL,
    subject_lead_id BIGINT NOT NULL,
    actor_user_id BIGINT REFERENCES users(id),
    actor_name VARCHAR(120) NOT NULL,
    type VARCHAR(48) NOT NULL,
    description VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX activities_lead_time_idx ON activities (lead_id, created_at DESC, id DESC);
