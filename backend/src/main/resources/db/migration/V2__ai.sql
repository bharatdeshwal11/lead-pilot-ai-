CREATE TABLE lead_analyses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    created_by bigint NOT NULL REFERENCES users(id),
    intent varchar(10) NOT NULL CHECK (intent IN ('HIGH', 'MEDIUM', 'LOW')),
    requirement varchar(240),
    budget varchar(180),
    timeline varchar(180),
    summary varchar(600) NOT NULL,
    next_action varchar(400) NOT NULL,
    recommended_priority varchar(10) NOT NULL CHECK (recommended_priority IN ('HIGH', 'MEDIUM', 'LOW')),
    uncertainty_notes varchar(400) NOT NULL,
    provider varchar(30) NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX lead_analyses_lead_created_idx ON lead_analyses(lead_id, created_at DESC, id DESC);

CREATE TABLE reply_drafts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    created_by bigint NOT NULL REFERENCES users(id),
    reviewed_by bigint REFERENCES users(id),
    body varchar(2500) NOT NULL CHECK (length(trim(body)) > 0),
    status varchar(16) NOT NULL CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    provider varchar(30) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    reviewed_at timestamptz,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT reply_drafts_review_metadata_check CHECK (
        (status IN ('APPROVED', 'REJECTED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        OR (status IN ('DRAFT', 'PENDING_REVIEW') AND reviewed_by IS NULL AND reviewed_at IS NULL)
    )
);

CREATE INDEX reply_drafts_lead_created_idx ON reply_drafts(lead_id, created_at DESC, id DESC);
