CREATE TABLE follow_ups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    assigned_user_id BIGINT NOT NULL REFERENCES users(id),
    note VARCHAR(500) NOT NULL CHECK (char_length(btrim(note)) > 0),
    due_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX follow_ups_lead_due_idx ON follow_ups (lead_id, due_at, id);
CREATE INDEX follow_ups_assignee_due_idx ON follow_ups (assigned_user_id, due_at, id);
CREATE INDEX follow_ups_open_due_idx ON follow_ups (due_at, id) WHERE completed_at IS NULL;
